#==============================================================================
# 02_Table1.R
# Baseline characteristics
#==============================================================================

rm(list = ls())

source("00_config.R")

library(tableone)
library(dplyr)

#------------------------------------------------------------------------------
# Load data
#------------------------------------------------------------------------------

metadata <- readRDS(
  file.path(data_dir, "metadata.rds")
)

#------------------------------------------------------------------------------
# Variable type
#------------------------------------------------------------------------------

metadata$SP <- factor(
  metadata$SP,
  levels = c(1,2),
  labels = c("Male","Female")
)

metadata$HYPERLIPIDEMIA_18 <- factor(
  metadata$HYPERLIPIDEMIA_18,
  levels = c(0,1),
  labels = c("Healthy","Hyperlipidemia")
)

#------------------------------------------------------------------------------
# Variables
#------------------------------------------------------------------------------

vars <- c(
  
  "IKA18",
  
  "BMI18",
  
  "WAIST18",
  
  "GLUCOSE18",
  
  "TRIGLY18",
  
  "LDLC18",
  
  "HDLC18",
  
  "SP"
  
)

factorVars <- c(
  
  "SP"
  
)

#------------------------------------------------------------------------------
# Table1
#------------------------------------------------------------------------------

table1 <- CreateTableOne(
  
  vars = vars,
  
  strata = "HYPERLIPIDEMIA_18",
  
  data = metadata,
  
  factorVars = factorVars,
  
  addOverall = TRUE
  
)

#------------------------------------------------------------------------------
# Print
#------------------------------------------------------------------------------

table1_print <- print(
  
  table1,
  
  quote = FALSE,
  
  noSpaces = TRUE,
  
  printToggle = FALSE
  
)

#------------------------------------------------------------------------------
# Save
#------------------------------------------------------------------------------

write.csv(
  
  table1_print,
  
  file.path(table_dir, "Table1.csv")
  
)

cat("=============================================\n")

cat("Table1 finished.\n")

cat("Saved to:\n")

cat(file.path(table_dir, "Table1.csv"), "\n")

cat("=============================================\n")